  const cache = new Map();
  function glyph(ch, color) {
    const key = color + ch;
    let c = cache.get(key);
    if (c) return c;
    const rows = G[ch];
    if (!rows) return null;
    c = mkCanvas(5, 7);
    const x = c.getContext('2d');
    x.fillStyle = color;
    for (let j = 0; j < 7; j++) for (let i = 0; i < 5; i++) if (rows[j][i] === '#') x.fillRect(i, j, 1, 1);
    cache.set(key, c);
    return c;
  }
  function width(str, scale = 1) { return Math.max(0, String(str).length * 6 * scale - scale); }
  function draw(ctx, str, x, y, opts = {}) {
    const color = opts.color || '#ffffff', scale = opts.scale || 1, align = opts.align || 'left';
    str = String(str).toUpperCase();
    const w = width(str, scale);
    if (align === 'center') x -= w / 2; else if (align === 'right') x -= w;
    x = Math.round(x); y = Math.round(y);
    if (opts.shadow) {
      const sc = opts.shadow === true ? '#000000' : opts.shadow;
      const off = opts.shadowOff || scale;
      for (let i = 0; i < str.length; i++) { const g = glyph(str[i], sc); if (g) ctx.drawImage(g, x + i * 6 * scale + off, y + off, 5 * scale, 7 * scale); }
    }
    if (opts.outline) {
      const oc = opts.outline;
      for (let i = 0; i < str.length; i++) {
        const g = glyph(str[i], oc); if (!g) continue;
        const gx = x + i * 6 * scale;
        ctx.drawImage(g, gx - scale, y, 5 * scale, 7 * scale); ctx.drawImage(g, gx + scale, y, 5 * scale, 7 * scale);
        ctx.drawImage(g, gx, y - scale, 5 * scale, 7 * scale); ctx.drawImage(g, gx, y + scale, 5 * scale, 7 * scale);
      }
    }
    for (let i = 0; i < str.length; i++) { const g = glyph(str[i], color); if (g) ctx.drawImage(g, x + i * 6 * scale, y, 5 * scale, 7 * scale); }
    return w;
  }
  // word-wrapped paragraph; returns lines drawn
  function drawWrapped(ctx, str, x, y, maxW, opts = {}) {
    const scale = opts.scale || 1, lh = (opts.lineHeight || 9) * scale;
    const words = String(str).split(' ');
    const lines = []; let cur = '';
    for (const w of words) { const test = cur ? cur + ' ' + w : w; if (width(test, scale) > maxW && cur) { lines.push(cur); cur = w; } else cur = test; }
    if (cur) lines.push(cur);
    lines.forEach((l, i) => draw(ctx, l, x, y + i * lh, opts));
    return lines.length;
  }
  return { draw, width, drawWrapped, glyph, H: 7 };
